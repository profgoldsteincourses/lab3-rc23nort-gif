# Simple loop using range()

# A function to print a series of names.
# It does not have any parameters
def printNames():
  for myName in ["Drake","Taylor","Billy"]:
        for lastName in ["Graham","Swift","Bob" ]:
             print (myName + " " + lastName)
# Call our function
printNames()
